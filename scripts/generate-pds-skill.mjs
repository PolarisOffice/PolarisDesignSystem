/* ── 쓰기 / --check ─────────────────────────────────────────────────── */
function readExisting() {
  const out = new Map();
  const walk = (dir, rel) => {
    if (!existsSync(dir)) return;
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(p, r);
      else out.set(r, readFileSync(p, 'utf8'));
    }
  };
  walk(OUT, '');
  return out;
}

const existing = readExisting();
const changed = [];
for (const [rel, content] of files) if (existing.get(rel) !== content) changed.push(rel);
for (const rel of existing.keys()) if (!files.has(rel)) changed.push(`${rel} (삭제)`);

if (check) {
  if (changed.length) {
    console.error(`[pds-skill --check] SKILL/ 이 정본과 다릅니다 (${changed.length}건) — node scripts/generate-pds-skill.mjs 로 재생성하세요:\n  ${changed.join('\n  ')}`);
    process.exit(1);
  }
  console.log('[pds-skill --check] clean');
} else {
  rmSync(OUT, { recursive: true, force: true });
  for (const [rel, content] of files) {
    const p = join(OUT, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
  console.log(`[pds-skill] SKILL/ — 컴포넌트 ${folders.length}개 (md 절 ${components.length}개 매칭, hash:${hash}) ${changed.length ? `갱신 ${changed.length}건` : '변경 없음'}`);
}

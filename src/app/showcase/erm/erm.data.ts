export const DEPARTMENTS = ['정보보안', '재무', '법무', '인사', '개발', '운영', '영업'] as const;
export const GRADES = ['높음', '중간', '낮음'] as const;
export const STATUSES = ['조치중', '모니터링', '지연', '완료'] as const;

export type Department = (typeof DEPARTMENTS)[number];
export type Grade = (typeof GRADES)[number];
export type Status = (typeof STATUSES)[number];

export interface Risk {
  id: string;
  title: string;
  plan: string;
  dept: Department;
  /** 발생 가능성 1~5 */
  likelihood: number;
  /** 영향도 1~5 */
  impact: number;
  owner: string;
  status: Status;
  /** 조치 기한 YYYY.MM.DD */
  due: string;
}

/** 점수 = 발생 가능성 × 영향도 (1~25) */
export const scoreOf = (r: Risk) => r.likelihood * r.impact;

/** 15 이상 높음 · 8 이상 중간 · 그 밖 낮음 */
export const gradeOf = (r: Risk): Grade => {
  const s = scoreOf(r);
  return s >= 15 ? '높음' : s >= 8 ? '중간' : '낮음';
};


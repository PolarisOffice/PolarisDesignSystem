/**
 * PDS 오프라인 스킬 트리 생성 — `designs/pds.md` + `packages/pds-react/src/components` → `packages/pds-react/SKILL/`.
 *
 * **왜 생성하는가**
 * npm 을 쓸 수 없는 환경(온프레미스)에서도 로컬 AI 가 PDS 를 그대로 쓰게 하려면, 규칙·예제(문서)와
 * 컴포넌트 소스가 한 묶음으로 필요하다. 문서는 손으로 쓰면 사본이 되어 어긋난다 — 문서 사이트에서
 * 기계 생성한 `pds.md` 를 한 번 더 파생해 만든다. 소스는 **복사하지 않는다**: `src/components/{이름}`
 * 을 정본 그대로 두고, `SKILL/references/{이름}/` 폴더명을 소스 폴더명과 1:1 로 맞춰 zip 조립 때
 * 폴더명으로 매칭한다(build-pds-skill-zip.mjs).
 *
 * **산출**
 *   SKILL/SKILL.md                      규칙(설치·배선·조합) + 카탈로그
 *   SKILL/references/{폴더명}/README.md  용도·사용 규칙·예제 (예제 import 는 로컬 경로로)
 *
 * 실행: node PDS/scripts/generate-pds-skill.mjs [--check]
 */
